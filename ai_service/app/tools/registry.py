"""Tool registry: the allowlist of everything the LLM may request.

The LLM only ever sees `name`, `description` and `input_schema`. Handlers,
permissions and confirmation rules stay server-side."""
from dataclasses import dataclass, field
from typing import Any, Awaitable, Callable

from app.adapters.base import LibraryToolAdapter
from app.auth.context import UserContext
from app.schemas.library import Role


@dataclass
class ToolDeps:
    """Server-side dependencies handed to handlers; never visible to the LLM."""
    adapter: LibraryToolAdapter
    retriever: Any = None      # RAG retriever (Phase 4)
    recommender: Any = None    # recommendation engine (Phase 5)


@dataclass
class ExecContext:
    user: UserContext | None
    deps: ToolDeps
    # Generated by the orchestrator for state-changing calls; never LLM-supplied
    idempotency_key: str | None = None


Handler = Callable[[ExecContext, dict], Awaitable[Any]]


@dataclass
class ToolSpec:
    name: str
    description: str
    input_schema: dict
    handler: Handler
    requires_auth: bool = False
    allowed_roles: set[Role] | None = None  # None = any role (subject to requires_auth)
    requires_confirmation: bool = False
    # Read-only check run before proposing a confirmation action (validates it is possible)
    precheck: Handler | None = None
    # Type the handler result must validate against (pydantic model or typing construct)
    output_type: Any = None

    def llm_declaration(self) -> dict:
        return {"name": self.name, "description": self.description, "parameters": self.input_schema}


@dataclass
class ToolRegistry:
    _tools: dict[str, ToolSpec] = field(default_factory=dict)

    def register(self, spec: ToolSpec) -> None:
        if spec.name in self._tools:
            raise ValueError(f"Tool {spec.name} already registered")
        self._tools[spec.name] = spec

    def get(self, name: str) -> ToolSpec | None:
        return self._tools.get(name)

    def names(self) -> list[str]:
        return list(self._tools)

    def declarations(self) -> list[dict]:
        # All tools are advertised; permissions are enforced at execution so that
        # unauthorized requests produce a deterministic, auditable refusal.
        return [t.llm_declaration() for t in self._tools.values()]
